"use strict";
const assert = require('node:assert/strict');
const M = require('../web/viz3d_math.js');
const near=(a,b,eps=1e-10)=>assert.ok(Math.abs(a-b)<=eps,`${a} != ${b}`);
const c={time_s:[0,.5,1,2],sprung_m:[0,.01,.02,.04],unsprung_m:[0,.02,.04,.06],road_m:[0,.05,.01,0]};
const saved=JSON.stringify(c);
for(const [t,expected] of [[-1,0],[0,0],[.25,.005],[.5,.01],[.75,.015],[1.5,.03],[2,.04],[50,.04]])near(M.sampleAt(c,t).sprung_m,expected);
assert.equal(M.sampleAt(c,.75).time_s,.75);
assert.equal(M.stateAt('quarter',{channels:c},.5).front_wheel_m,.02);
assert.equal(M.stateAt('quarter',{channels:c},.5).body_m,.01);
assert.equal(M.stateAt('quarter',{channels:c},.5).front_road_m,.05);
assert.equal(JSON.stringify(c),saved,'presentation must never mutate numerical channels');
const half={channels:{time_s:[0,1],body_heave_m:[0,.02],body_pitch_rad:[0,.03],front_wheel_m:[0,.05],rear_wheel_m:[0,.01],front_road_m:[0,.04],rear_road_m:[0,0]}};
near(M.stateAt('half',half,.5).pitch_rad,.015);
near(M.stateAt('half',half,.5).rear_wheel_m,.005);
const brake={channels:{time_s:[0,4],speed_m_s:[20,0],distance_m:[0,40],front_normal_n:[6000,8000],rear_normal_n:[6000,4000]}};
near(M.stateAt('braking',brake,4).speed_m_s,0);
near(M.stateAt('braking',brake,4).distance_m,40);
assert.equal(M.stateAt('braking',brake,2).pitch_rad,0,'braking does not infer body pitch');
const regen={channels:{...brake.channels,cumulative_battery_energy_j:[0,76640],regen_force_n:[4000,0],friction_force_n:[2000,0]}};
near(M.stateAt('regen',regen,4).battery_j,76640);
assert.equal(M.stateAt('regen',regen,4).speed_m_s,0);
const cam={yaw:Math.PI/3,elevation:.4,zoom:100};
assert.deepEqual(M.project([0,0,0],cam,600,300),{x:300,y:180,depth:0});
assert.ok(M.project([0,1,0],cam,600,300).y<180);
assert.throws(()=>M.sampleAt(null,1),/Missing/);
assert.throws(()=>M.stateAt('invalid',{channels:c},1),/Unknown/);
console.log('23 presentation math, time-alignment, orientation, no-mutation assertions passed');
